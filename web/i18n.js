export const messages = { zh, en, ja };

export function isLanguage(value) {
  return Object.hasOwn(messages, value);
}

export function format(template, params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => (params[key] === undefined || params[key] === null ? match : String(params[key])));
}

export function translate(language, key, params) {
  const table = messages[isLanguage(language) ? language : 'zh'];
  const template = table[key] ?? messages.zh[key];
  if (template === undefined) return params && params.fallback ? params.fallback : key;
  return format(template, params);
}

export function localeOf(language) {
  return (languages.find(item => item.id === language) || languages[0]).locale;
}
